import pandas as pd
import numpy as np
import statsmodels.api as sm

CSV = next((c for c in ['quarterly_SO2_data.csv', 'quarterly_SO2_data/quarterly_SO2_data.csv']
            if os.path.exists(c)), 'quarterly_SO2_data.csv')
df = pd.read_csv(CSV)
print(df.head())

# 2. Create Quarter Dummies (Q1 is reference category)
df_dummies = pd.get_dummies(df.copy(), columns=['quarter'], drop_first=True, dtype=int)

# Predictor columns
X_cols = ['temperature', 'windspeed', 'precipitation', 'precipitationdays', 'manufacturing_enterprises',
          'population_thousands',
          'quarter_2', 'quarter_3', 'quarter_4']

# Response variable
y_col = 'SO2'

# Predictor choice (we keep all nine, on purpose):
#  Weather: temperature, windspeed, precipitation, precipitationdays = the weather part of the research question.
#  Industry & size: manufacturing_enterprises, population_thousands = city-level pollution sources.
#  Season: quarter_2..quarter_4 (Q1 = baseline) = seasonal shifts such as heating.
#  We do NOT drop manufacturing or population even though r = 0.96 (VIF about 13): we want to predict, and
#  collinearity does not harm prediction, it only stops us reading the two slopes one at a time.
#  windspeed is kept so the model matches the other models, but its Memphis and Charleston values are
#  impossible (about 92 and 65 mph) - see the robustness check further down.

# Constant for intercept (beta_0)
X = sm.add_constant(df_dummies[X_cols])
y = df_dummies[y_col]

# Run regression
model = sm.OLS(y, X).fit()
print(model.summary())

# The 492 rows are 41 cities x 12 quarters, so rows from one city are strongly related (Durbin-Watson above
# is 0.15, far from 2). The ordinary standard errors above are therefore too small. Cluster by city instead:
city_id = df_dummies['city'].astype('category').cat.codes
model_cl = sm.OLS(y, X).fit(cov_type='cluster', cov_kwds={'groups': city_id})
compare = pd.DataFrame({'coef': model.params, 'se_ordinary': model.bse, 'se_clustered': model_cl.bse,
                        'p_ordinary': model.pvalues, 'p_clustered': model_cl.pvalues}).round(4)
print("\n=== Ordinary vs city-clustered standard errors (USE THE CLUSTERED p-VALUES) ===")
print(compare)

print("========MODEL COEF===============")
# Fitted model equation
coefs = model.params
print(coefs)
print("\n" + "=" * 50)
print("=== FITTED MODEL EQUATION ===")
print("=" * 50)
print(f"SO2_hat = {coefs['const']:.4f} "
      f"+ ({coefs['temperature']:.4f} * Temp) "
      f"+ ({coefs['windspeed']:.4f} * Wind) "
      f"+ ({coefs['precipitation']:.4f} * Precip) "
      f"+ ({coefs['precipitationdays']:.4f} * PrecDays) "
      f"+ ({coefs['manufacturing_enterprises']:.4f} * Manu) "
      f"+ ({coefs['population_thousands']:.4f} * Pop) "
      f"+ ({coefs['quarter_2']:.4f} * Q2) "
      f"+ ({coefs['quarter_3']:.4f} * Q3) "
      f"+ ({coefs['quarter_4']:.4f} * Q4)")

"""Interpreting the coefficients (p-values are from city-clustered standard errors, because the 492 rows are
only 41 independent cities; the ordinary p-values would overstate significance).

Intercept: 43.41 (p < 0.001) is the predicted SO2 in quarter 1 when every numerical predictor is zero. It is
outside the range of the data, so it is not interpretable on its own.

Temperature: -0.581 ug/m3 per degree F (p = 0.010). Significant. Cities and quarters that are 1 F warmer have about
0.58 lower SO2 on average, holding the other variables fixed. This is an association; it is consistent with more
heating fuel being burned in cold conditions, but this data cannot show the cause.

Manufacturing enterprises: +0.070 per enterprise (p < 0.001); Population: -0.046 per thousand people (p = 0.002).
Both significant, but the two are 96% correlated (VIF about 13), so read them together: cities with many factories
relative to their population have higher SO2. Neither slope should be interpreted alone.

Wind speed: -0.085 (p = 0.21) and precipitation: +0.278 (p = 0.20) are NOT significant once the clustering is
accounted for. Precipitation days (+0.123, p = 0.71) and the quarter indicators Q2, Q3, Q4 (p = 0.40, 0.38, 0.23)
are not significant either. (The ordinary p-values of 0.049 for wind speed and < 0.001 for precipitation came from
treating the rows as independent and should not be quoted.) The wind speed slope is also distorted: Memphis (about
92 mph) and Charleston (about 65 mph) report impossible values in every quarter. Without those two cities the slope
is -2.6 per mph (clustered p = 0.10), so there is some sign of a negative wind effect, but the data is too thin to
claim it.

Model fit and predictive performance: R-squared is 0.64 on the 41 cities we have, but the fair figure for a NEW city
is the leave-one-city-out result at the bottom: pooled R-squared 0.553, RMSE 16.0 against 24.0 for the naive guess
(k = 0), and RMSE 2.75 and 2.09 after one and two quarters of readings. So the model predicts a new city moderately
well, not accurately. Collinearity between manufacturing and population does not hurt this prediction; it only makes
the two individual slopes hard to read.

Assumption checks: the residuals are right-skewed (skew 0.87, Shapiro-Wilk p < 0.001) and their spread is not
constant (Breusch-Pagan p < 0.001), so a log transform of SO2 would be the natural next step; and the residuals are
almost entirely city-level (98% of residual variance is between cities), which is why the clustered standard errors
are the correct ones. Chicago has a strong pull on the fit: R-squared falls from 0.64 to 0.49 without it.
"""

import matplotlib.pyplot as plt
from scipy import stats
from statsmodels.stats.outliers_influence import variance_inflation_factor
from statsmodels.stats.diagnostic import het_breuschpagan

resid = model.resid
fitted = model.fittedvalues

fig, ax = plt.subplots(2, 2, figsize=(12, 9))
ax[0,0].scatter(fitted, resid, alpha=.6); ax[0,0].axhline(0, color='r')
ax[0,0].set(title='Resi vs fit', xlabel='Fit SO2', ylabel='Resid')
sm.qqplot(resid, line='s', ax=ax[0,1]); ax[0,1].set_title('Normal QQ plot')
ax[1,0].hist(resid, bins=30, edgecolor='k'); ax[1,0].set_title('Resid histogram')
df_dummies['resid'] = resid
order = df_dummies.groupby('city')['resid'].mean().sort_values().index
ax[1,1].boxplot([df_dummies.loc[df_dummies.city == c, 'resid'] for c in order])
ax[1,1].axhline(0, color='r'); ax[1,1].set_xticks([])
ax[1,1].set_title('Resid by city')
plt.tight_layout(); plt.show()

print("Shapiro-Wilk:", stats.shapiro(resid))
print("Skew:", stats.skew(resid), " Excess kurtosis:", stats.kurtosis(resid))
print("Breusch-Pagan p-value:", het_breuschpagan(resid, X)[1])
vif = pd.Series([variance_inflation_factor(X.values, i) for i in range(1, X.shape[1])],
                index=X.columns[1:])
print(vif.round(1))
print("corr(manu, pop):", df['manufacturing_enterprises'].corr(df['population_thousands']))
print("Share of residual variance between cities:",
      (df_dummies.groupby('city')['resid'].mean()**2).mean() / (resid**2).mean())

# --- Robustness checks (they support the interpretation text above) ---
def clustered(sub):
    Xs = sm.add_constant(sub[X_cols]); cid = sub['city'].astype('category').cat.codes
    return sm.OLS(sub['SO2'], Xs).fit(cov_type='cluster', cov_kwds={'groups': cid})

no_wind_err = clustered(df_dummies[~df_dummies.city.isin(['Memphis', 'Charleston'])])
print("\nWithout Memphis and Charleston: windspeed coef %.3f, clustered p = %.3f" %
      (no_wind_err.params['windspeed'], no_wind_err.pvalues['windspeed']))
no_chi = sm.OLS(df_dummies.loc[df_dummies.city != 'Chicago', 'SO2'],
                sm.add_constant(df_dummies.loc[df_dummies.city != 'Chicago', X_cols])).fit()
print("R-squared with Chicago %.3f, without Chicago %.3f" % (model.rsquared, no_chi.rsquared))

df = df.sort_values(['city', 'year', 'quarter']).reset_index(drop=True)
d  = pd.get_dummies(df, columns=['quarter'], drop_first=True, dtype=int)

def loco(k):
    y_true, y_pred, y_naive = [], [], []
    for c in d['city'].unique():
        train, test = d[d.city != c], d[d.city == c]
        m = sm.OLS(train['SO2'], sm.add_constant(train[X_cols])).fit()
        pred = m.predict(sm.add_constant(test[X_cols], has_constant='add')).values
        obs  = test['SO2'].values
        if k > 0:
            pred = pred + (obs[:k] - pred[:k]).mean()
        y_true.append(obs[k:]); y_pred.append(pred[k:])
        y_naive.append(np.full(12 - k, train['SO2'].mean()))
    y_true, y_pred, y_naive = map(np.concatenate, (y_true, y_pred, y_naive))
    rmse = np.sqrt(np.mean((y_true - y_pred)**2))
    r2   = 1 - np.sum((y_true - y_pred)**2) / np.sum((y_true - y_naive)**2)
    return rmse, r2

results = pd.DataFrame([(k, *loco(k)) for k in (0, 1, 2)],
                       columns=['k', 'Pooled RMSE', 'Pooled R2']).round(3)
print(results)
